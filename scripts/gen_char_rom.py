#!/usr/bin/env python3
"""Generate the latency-OSD character ROM artefacts from one upstream font.

Upstream input (public domain, provenance recorded in work/models/third_party/README.md):
    work/models/third_party/font8x8_basic.h

Generated outputs (never edit by hand; regenerate with this script):
    work/models/font8x8_public_domain.py    Python glyph table (index 0 -> code 0x20)
    work/rtl/osd/char_rom.v                 synthesizable 95 x 8 ROM for the FPGA overlay

Usage:
    python scripts/gen_char_rom.py            # write both outputs
    python scripts/gen_char_rom.py --check    # fail if outputs are stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "work/models/third_party/font8x8_basic.h"
PY_OUT = ROOT / "work/models/font8x8_public_domain.py"
V_OUT = ROOT / "work/rtl/osd/char_rom.v"

FIRST_CODE = 0x20  # ' '
LAST_CODE = 0x7E   # '~'
GLYPH_ROWS = 8
GLYPH_COLS = 8     # bit 0 is the leftmost pixel, bit 7 the rightmost


def parse_upstream(path: Path) -> list[tuple[int, ...]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    body = text.split("font8x8_basic[128][8] = {", 1)[1]
    body = body.split("\n};", 1)[0]
    glyphs = []
    for block in re.finditer(r"\{([^{}]*)\}", body):
        values = re.findall(r"0x([0-9A-Fa-f]{2})", block.group(1))
        if len(values) != GLYPH_ROWS:
            raise SystemExit(f"unexpected glyph width in {path}")
        glyphs.append(tuple(int(v, 16) for v in values))
    if len(glyphs) < LAST_CODE + 1:
        raise SystemExit(f"expected >= {LAST_CODE + 1} glyphs, found {len(glyphs)}")
    return glyphs


def render_python(glyphs: list[tuple[int, ...]]) -> str:
    lines = [
        '"""8x8 bitmap font table for the latency OSD (generated, do not edit).',
        "",
        "Generated by scripts/gen_char_rom.py from",
        "work/models/third_party/font8x8_basic.h (public domain).",
        '"""',
        "",
        "FONT_FIRST_CODE = %#04x" % FIRST_CODE,
        "FONT_LAST_CODE = %#04x" % LAST_CODE,
        "GLYPH_ROWS = %d" % GLYPH_ROWS,
        "GLYPH_COLS = %d" % GLYPH_COLS,
        "LEFTMOST_BIT = 0  # bit 0 of every row byte is the leftmost pixel",
        "",
        "FONT_ROWS = (",
    ]
    for code in range(FIRST_CODE, LAST_CODE + 1):
        ch = chr(code)
        label = "space" if ch == " " else ch
        body = ", ".join("0x%02X" % b for b in glyphs[code])
        lines.append("    (%s),  # %#04x %r" % (body, code, label))
    lines.append(")")
    lines.append("")
    lines.append("GLYPH_COUNT = FONT_LAST_CODE - FONT_FIRST_CODE + 1")
    lines.append("")
    lines.append("")
    lines.append("def glyph_rows(char: str):")
    lines.append('    """Return the eight row bytes of ``char`` (blank if out of range)."""')
    lines.append("    index = ord(char[0]) - FONT_FIRST_CODE")
    lines.append("    if index < 0 or index >= GLYPH_COUNT:")
    lines.append("        return (0,) * GLYPH_ROWS")
    lines.append("    return FONT_ROWS[index]")
    lines.append("")
    return "\n".join(lines)


def render_verilog(glyphs: list[tuple[int, ...]]) -> str:
    lines = [
        "//======================================================================",
        "// char_rom.v - 95 x 8 bit character ROM for the latency/OSD text overlay",
        "//",
        "// GENERATED FILE - do not edit by hand.",
        "//   generator: scripts/gen_char_rom.py",
        "//   font     : work/models/third_party/font8x8_basic.h (public domain)",
        "//   mirror   : work/models/font8x8_public_domain.py (Python golden model)",
        "//",
        "// char_code : ASCII 0x20..0x7E. Any other code selects a blank cell.",
        "// row       : 0 = top scanline of the glyph cell.",
        "// bits      : bit 0 = leftmost pixel, bit 7 = rightmost pixel.",
        "//",
        "// Eight row bytes are packed into one 64-bit constant per character and",
        "// sliced with a variable part-select, so the ROM contains no divider and",
        "// no per-row case duplication.",
        "//======================================================================",
        "`timescale 1ns/1ps",
        "",
        "module char_rom (",
        "    input  wire [6:0] char_code,  // ASCII 0x20..0x7E",
        "    input  wire [2:0] row,        // 0 = top row",
        "    output wire [7:0] bits        // bit 0 = leftmost pixel",
        ");",
        "    reg [63:0] glyph;",
        "",
        "    always @(*) begin",
        "        case (char_code)",
    ]
    for code in range(FIRST_CODE, LAST_CODE + 1):
        g = glyphs[code]
        packed = 0
        for row_index, byte in enumerate(g):
            packed |= byte << ((GLYPH_ROWS - 1 - row_index) * 8)
        ch = chr(code)
        label = "space" if ch == " " else ch
        lines.append("            7'h%02X: glyph = 64'h%016X;  // '%s'" % (code, packed, label))
    lines += [
        "            default: glyph = 64'h0;  // blank for codes outside 0x20..0x7E",
        "        endcase",
        "    end",
        "",
        "    assign bits = glyph[(7 - row) * 8 +: 8];",
        "",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify outputs are up to date")
    args = parser.parse_args()

    glyphs = parse_upstream(UPSTREAM)
    outputs = {PY_OUT: render_python(glyphs), V_OUT: render_verilog(glyphs)}

    stale = []
    for path, text in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote %s" % path.relative_to(ROOT).as_posix())

    if args.check and stale:
        for path in stale:
            print("STALE: %s" % path.relative_to(ROOT).as_posix(), file=sys.stderr)
        return 1
    if args.check:
        print("char_rom artefacts up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
