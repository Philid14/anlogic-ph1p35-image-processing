"""Refresh TD run project source lists from the tracked .al before CLI builds.

TD's .al text contains an unescaped '&' in attribute names, so preserve its
native format rather than parsing/reformatting with a standard XML library.
Existing TD settings.cfg must have been generated by opening the project once.
"""
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "in_out_example/lab_ex3_osd_SC500_720P/lab_ex3_osd/td_project"
NAME = "camera_to_dsi_display"


def main():
    text = (PROJECT / f"{NAME}.al").read_text(encoding="utf-8")
    for run in ("syn_1", "phy_1"):
        directory = PROJECT / f"{NAME}_Runs" / run
        if not (directory / "settings.cfg").exists():
            raise RuntimeError("Open the .al in TD to generate run settings first")
        prepared = re.sub(
            r'<Project Version="3" Minor="2" Path="[^"]*">',
            '<Project Version="3" Minor="2" RunTime="2026-10-10T00:00:00">',
            text, count=1,
        )
        prepared = re.sub(r'(<File Path=")([^\"]+)(")',
                          lambda m: m[1] + "../../" + m[2] + m[3], prepared)
        prepared = re.sub(r"    <Runs>.*?</Runs>\s*", "", prepared, flags=re.S)
        prepared = re.sub(r"    <Project_Settings>.*?</Project_Settings>\s*", "", prepared, flags=re.S)
        (directory / f"{NAME}.prj").write_text(prepared, encoding="utf-8")
        for name in ('style_logo_index.dath','style_logo_palette.dath'):
            canonical=PROJECT.parent/'user_source/hdl_source/target'/name
            if canonical.is_file():
                assert canonical.read_bytes()==(PROJECT/name).read_bytes(),name
                shutil.copy2(canonical,directory/name)
        print(f"Prepared {run}: {len(re.findall('<File Path=', prepared))} source/IP/constraint entries")


if __name__ == "__main__":
    main()
