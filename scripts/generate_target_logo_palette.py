"""Lossless representation of the frozen Logo; no image resampling or recoloring.

The original sparse combinational case remains the reference. Two synchronous
ROM reads are prefetched at the undelayed mixer coordinate, matching its existing
two coordinate registers. Generated RTL uses explicit initial values so TD and
simulation do not depend on a working-directory-relative memory file.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HDL = ROOT / 'in_out_example/lab_ex3_osd_SC500_720P/lab_ex3_osd/user_source/hdl_source'


def generate():
    source = (HDL / 'anlogic_logo_rom.v').read_text()
    pixels = {int(a): int(v, 16) for a, v in re.findall(
        r"15'd(\d+): O_pixel = 25'h([0-9a-fA-F]+)", source)}
    assert len(pixels) == 6387
    palette = [0] + sorted(set(pixels.values()))
    lookup = {v: i for i, v in enumerate(palette)}
    assert len(palette) == 580 and min(pixels) >= 5440 and max(pixels) < 20480
    lines = ['// Generated by scripts/generate_target_logo_palette.py; lossless frozen Logo.',
             'module target_logo_palette(input clk, input [14:0] address,',
             '    output reg [24:0] pixel);',
             '    reg [9:0] index_rom[0:16383]; // synthesis ram_style=bram',
             '    reg [24:0] palette_rom[0:1023]; // synthesis ram_style=bram',
             '    reg [9:0] index;']
    indices = sum(lookup.get(pixels.get(i+5440, 0), 0) << (i*10) for i in range(16384))
    colors = sum((palette[i] if i < len(palette) else 0) << (i*25) for i in range(1024))
    for name, bits, value in [('INDEX_INIT',163840,indices),('PALETTE_INIT',25600,colors)]:
        digits=f'{value:0{bits//4}x}'
        chunks=[digits[i:i+256] for i in range(0,len(digits),256)]
        lines += [f'    localparam [{bits-1}:0] {name}={{']
        lines += ["        1024'h"+chunk+(',' if i<len(chunks)-1 else '};') for i,chunk in enumerate(chunks)]
    lines += ['    integer k;', '    initial begin',
              '        for(k=0;k<16384;k=k+1) index_rom[k]=INDEX_INIT[10*k+:10];',
              '        for(k=0;k<1024;k=k+1) palette_rom[k]=PALETTE_INIT[25*k+:25];']
    lines += ['    end', '    always @(posedge clk) begin',
              "        if(address>=15'd5440 && address<15'd20480)",
              "            index<=index_rom[address-15'd5440];",
              '        else index<=0;', '        pixel<=palette_rom[index];',
              '    end', 'endmodule', '']
    path = HDL / 'target/target_logo_palette.v'
    path.write_text('\n'.join(lines), encoding='utf-8')
    # Exhaustive content equivalence over the complete original 15-bit port.
    for a in range(32768):
        code = lookup.get(pixels.get(a, 0), 0) if 5440 <= a < 20480 else 0
        assert palette[code] == pixels.get(a, 0)
    print('Generated', path.name, 'colors', len(palette), '32768 content checks PASS')


if __name__ == '__main__':
    generate()
