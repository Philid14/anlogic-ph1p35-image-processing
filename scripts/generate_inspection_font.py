def main():
    old=FONT.read_text(encoding='utf-8')
    chinese=[]
    for name in ('AN','LU'):
        m=re.search(r'CHAR_'+name+r': begin(.*?)endcase\s*end',old,re.S)
        assert m;chinese.append('            CHAR_'+name+': begin'+m[1]+'endcase\n            end')
    text='// Unified original monospaced 5x7 ASCII; generated by scripts/generate_inspection_font.py\n'
    text+='module osd_char_lib(input wire [7:0] I_char,input wire [3:0] I_row,output reg [15:0] O_row_bits);\n'
    text+="    localparam CHAR_AN=8'h80, CHAR_LU=8'h81;\n"
    names={c:('CHAR_'+c if c.isalnum() else {':':'CHAR_COLON','.':'CHAR_DOT','-':'CHAR_DASH','/':'CHAR_SLASH','+':'CHAR_PLUS'}[c]) for c in GLYPHS}
    for c,n in names.items():text+=f"    localparam {n} = 8'h{ord(c):02x};\n"
    # Keep AN and LU separately parseable by the independent test model.
    text=text.replace("localparam CHAR_AN=8'h80, CHAR_LU=8'h81;","localparam CHAR_AN = 8'h80;\n    localparam CHAR_LU = 8'h81;")
    text+='    always @* begin\n        case(I_char)\n'+'\n'.join(chinese)+'\n'
    for c,rows in GLYPHS.items():
        bitmap=[0]+[int('000'+''.join(b*2 for b in row)+'000',2) for row in rows for _ in range(2)]+[0]
        text+=f'            {names[c]}: begin\n                case(I_row)\n'
        for row,bits in enumerate(bitmap):text+=f"                    4'd{row}: O_row_bits = 16'h{bits:04x};\n"
        text+="                    default: O_row_bits = 16'h0000;\n                endcase\n            end\n"
    text+="            default: O_row_bits=16'h0000;\n        endcase\n    end\nendmodule\n"
    FONT.write_text(text,encoding='utf-8')
if __name__=='__main__':main()
